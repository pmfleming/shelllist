use anyhow::{Result, ensure};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use std::{collections::BTreeSet, fs, path::Path};

const RESERVED: &[&str] = &[
    "open",
    "toggle",
    "floating",
    "hide",
    "quit",
    "status",
    "responsiveness",
    "list",
    "daemon",
    "run",
    "help",
    "shell",
    "update-logs",
    "volume-up",
    "volume-down",
    "volume-mute",
    "microphone-mute",
    "brightness-up",
    "brightness-down",
];
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Catalog {
    schema_version: u32,
    default_surface: String,
    surfaces: Vec<Surface>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Surface {
    id: String,
    name: String,
    icon: String,
    loading: String,
    resident_state: Value,
    home_manager_shortcut: Value,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Shortcut {
    option: String,
    default: Value,
    description: String,
}
fn text(value: &str) -> bool {
    !value.trim().is_empty() && !value.chars().any(|c| (c as u32) < 32)
}
pub fn render(input: &str) -> Result<String> {
    let catalog: Catalog = serde_json::from_str(input)?;
    ensure!(
        catalog.schema_version == 1 && !catalog.surfaces.is_empty(),
        "unsupported version or empty catalog"
    );
    let id_pattern = regex::Regex::new(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")?;
    let shortcut_pattern = regex::Regex::new(r"^[a-z][A-Za-z0-9]*Shortcut$")?;
    let (mut ids, mut options, mut bindings, mut residents) = (
        BTreeSet::new(),
        BTreeSet::new(),
        BTreeSet::new(),
        BTreeSet::new(),
    );
    for surface in &catalog.surfaces {
        ensure!(
            id_pattern.is_match(&surface.id)
                && !RESERVED.contains(&surface.id.as_str())
                && ids.insert(surface.id.clone()),
            "unsafe, reserved or duplicate ID: {}",
            surface.id
        );
        ensure!(
            text(&surface.name) && text(&surface.icon),
            "missing name/icon"
        );
        ensure!(
            ["eager", "lazy"].contains(&surface.loading.as_str()),
            "invalid loading policy"
        );
        ensure!(
            surface.resident_state.is_null() || surface.resident_state == "notifications",
            "unsupported resident state"
        );
        if surface.resident_state == "notifications" {
            residents.insert("notifications");
        }
        if !surface.home_manager_shortcut.is_null() {
            let shortcut: Shortcut = serde_json::from_value(surface.home_manager_shortcut.clone())?;
            ensure!(
                shortcut_pattern.is_match(&shortcut.option)
                    && shortcut.option != "updateLogsShortcut"
                    && options.insert(shortcut.option),
                "invalid/duplicate shortcut option"
            );
            ensure!(text(&shortcut.description), "missing shortcut description");
            if !shortcut.default.is_null() {
                let binding = shortcut
                    .default
                    .as_str()
                    .ok_or_else(|| anyhow::anyhow!("invalid shortcut default"))?;
                ensure!(
                    text(binding)
                        && binding.matches(',').count() == 1
                        && binding != "SUPER SHIFT, U"
                        && bindings.insert(binding.to_owned()),
                    "invalid/duplicate shortcut default"
                );
            }
        }
    }
    ensure!(
        ids.contains(&catalog.default_surface),
        "default surface is not registered"
    );
    let values = [
        ("defaultSurface", json!(catalog.default_surface)),
        (
            "descriptors",
            json!(
                catalog
                    .surfaces
                    .iter()
                    .map(|s| json!({"id":s.id,"name":s.name,"icon":s.icon}))
                    .collect::<Vec<_>>()
            ),
        ),
        (
            "eagerSurfaceIds",
            json!(
                catalog
                    .surfaces
                    .iter()
                    .filter(|s| s.loading == "eager")
                    .map(|s| &s.id)
                    .collect::<Vec<_>>()
            ),
        ),
        ("residentStateIds", json!(residents)),
        (
            "shortcuts",
            json!(
                catalog
                    .surfaces
                    .iter()
                    .map(|s| json!({"id":s.id,"description":format!("Toggle Shelllist {}",s.name)}))
                    .collect::<Vec<_>>()
            ),
        ),
    ];
    let mut output = ".pragma library\n// Generated by cargo xtask surfaces from contracts/surface-catalog.json.\n// Do not edit; typed factories stay in SurfaceRegistry.qml.\n\n".to_owned();
    for (name, value) in values {
        let mut bytes = Vec::new();
        value.serialize(&mut serde_json::Serializer::with_formatter(
            &mut bytes,
            serde_json::ser::PrettyFormatter::with_indent(b"    "),
        ))?;
        output.push_str(&format!("var {name} = {};\n\n", String::from_utf8(bytes)?));
    }
    output.push_str("// Each registry owns its mutable loading state, even in multi-engine tests.\nfunction initiallyLoaded() {\n    const result = {};\n    eagerSurfaceIds.forEach(function (id) { result[id] = true; });\n    return result;\n}\n\nfunction requiresResidentState(id) {\n    return residentStateIds.indexOf(id) !== -1;\n}\n");
    Ok(output)
}
pub fn generate(root: &Path, check: bool) -> Result<()> {
    let expected = render(&fs::read_to_string(
        root.join("contracts/surface-catalog.json"),
    )?)?;
    let output = root.join("shell/SurfaceCatalog.generated.js");
    if check {
        ensure!(
            fs::read_to_string(output).ok().as_ref() == Some(&expected),
            "stale surface catalog; run cargo xtask surfaces"
        );
    } else {
        fs::write(output, expected)?;
    }
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    fn catalog() -> Value {
        serde_json::from_str(include_str!("../../../contracts/surface-catalog.json")).unwrap()
    }
    #[test]
    fn schema_and_reserved_names_fail_closed() {
        for id in RESERVED.iter().copied().chain([
            "wifi",
            "WiFi",
            "new_panel",
            "a|b",
            "x;true",
            "$(touch foo)",
            "",
        ]) {
            let mut c = catalog();
            c["surfaces"][0]["id"] = json!(id);
            assert!(render(&c.to_string()).is_err(), "{id}");
        }
        for (pointer, bad) in [
            ("/schema_version", json!(true)),
            ("/default_surface", json!("unknown")),
            ("/surfaces/0/loading", json!("other")),
            ("/surfaces/0/resident_state", json!("other")),
            ("/surfaces/0/name", json!("\n")),
            ("/surfaces/0/icon", Value::Null),
        ] {
            let mut c = catalog();
            *c.pointer_mut(pointer).unwrap() = bad;
            assert!(render(&c.to_string()).is_err(), "{pointer}");
        }
        let mut c = catalog();
        c["extra"] = json!(1);
        assert!(render(&c.to_string()).is_err());
        c = catalog();
        c["surfaces"][0]
            .as_object_mut()
            .unwrap()
            .remove("resident_state");
        assert!(render(&c.to_string()).is_err());
    }
    #[test]
    fn shortcuts_reject_conflicts_and_invalid_defaults() {
        for default in [
            json!("SUPER SHIFT, U"),
            json!("no comma"),
            json!(4),
            json!("A,B,C"),
        ] {
            let mut c = catalog();
            c["surfaces"][0]["home_manager_shortcut"] =
                json!({"option":"testShortcut","default":default,"description":"Test"});
            assert!(render(&c.to_string()).is_err());
        }
        for option in ["updateLogsShortcut", "BadShortcut", "a-shortcut"] {
            let mut c = catalog();
            c["surfaces"][0]["home_manager_shortcut"] =
                json!({"option":option,"default":null,"description":"Test"});
            assert!(render(&c.to_string()).is_err());
        }
        let mut c = catalog();
        let shortcut = json!({"option":"testShortcut","default":"SUPER, Z","description":"Test"});
        c["surfaces"][0]["home_manager_shortcut"] = shortcut.clone();
        c["surfaces"][1]["home_manager_shortcut"] = shortcut;
        assert!(render(&c.to_string()).is_err());
    }
    #[test]
    fn freshness_missing_edits_and_metadata_changes() {
        let temp = tempfile::tempdir().unwrap();
        let root = temp.path();
        fs::create_dir(root.join("contracts")).unwrap();
        fs::create_dir(root.join("shell")).unwrap();
        let mut c = catalog();
        fs::write(root.join("contracts/surface-catalog.json"), c.to_string()).unwrap();
        assert!(generate(root, true).is_err());
        generate(root, false).unwrap();
        generate(root, true).unwrap();
        c["surfaces"][0]["icon"] = json!("changed");
        fs::write(root.join("contracts/surface-catalog.json"), c.to_string()).unwrap();
        assert!(generate(root, true).is_err());
        generate(root, false).unwrap();
        fs::write(root.join("shell/SurfaceCatalog.generated.js"), "hand edit").unwrap();
        assert!(generate(root, true).is_err());
    }
}
