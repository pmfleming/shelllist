#!/usr/bin/env python3
"""Generate build-time QML metadata; never generate controller factories or effects."""
import argparse
import json
from pathlib import Path
import re
import sys

# Host commands and non-surface shortcut names must not shadow catalog IDs.
RESERVED_IDS = {
    "open", "toggle", "floating", "hide", "quit", "status", "responsiveness",
    "list", "daemon", "run", "help", "shell", "update-logs", "volume-up",
    "volume-down", "volume-mute", "microphone-mute", "brightness-up", "brightness-down",
}
ROOT_KEYS = {"schema_version", "default_surface", "surfaces"}
SURFACE_KEYS = {"id", "name", "icon", "loading", "resident_state", "home_manager_shortcut"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def text(value):
    return isinstance(value, str) and bool(value.strip()) and not any(ord(c) < 32 for c in value)


def validate(catalog):
    require(isinstance(catalog, dict) and set(catalog) == ROOT_KEYS, "invalid catalog keys")
    require(type(catalog["schema_version"]) is int and catalog["schema_version"] == 1, "unsupported catalog version")
    surfaces = catalog["surfaces"]
    require(isinstance(surfaces, list) and bool(surfaces), "surfaces must be a nonempty list")
    ids, options, bindings = set(), set(), set()
    for surface in surfaces:
        require(isinstance(surface, dict) and set(surface) == SURFACE_KEYS, "invalid surface keys")
        ident = surface["id"]
        require(isinstance(ident, str) and re.fullmatch(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*", ident), "unsafe surface ID")
        require(ident not in ids and ident not in RESERVED_IDS, f"duplicate/reserved surface ID: {ident}")
        ids.add(ident)
        require(text(surface["name"]) and text(surface["icon"]), f"missing name/icon: {ident}")
        require(surface["loading"] in ("eager", "lazy"), f"invalid loading policy: {ident}")
        # Every resident-state kind needs an explicit typed owner in the registry.
        require(surface["resident_state"] in (None, "notifications"), f"unsupported resident state: {ident}")
        shortcut = surface["home_manager_shortcut"]
        if shortcut is None:
            continue
        require(isinstance(shortcut, dict) and set(shortcut) == {"option", "default", "description"}, f"invalid shortcut: {ident}")
        option = shortcut["option"]
        require(isinstance(option, str) and re.fullmatch(r"[a-z][A-Za-z0-9]*Shortcut", option), f"invalid shortcut option: {ident}")
        require(option not in options and option != "updateLogsShortcut", f"duplicate/reserved shortcut option: {option}")
        require(text(shortcut["description"]), f"missing shortcut description: {ident}")
        binding = shortcut["default"]
        require(binding is None or (text(binding) and binding.count(",") == 1), f"invalid shortcut default: {ident}")
        require(binding is None or (binding not in bindings and binding != "SUPER SHIFT, U"), f"duplicate/reserved shortcut default: {ident}")
        options.add(option)
        if binding is not None:
            bindings.add(binding)
    require(isinstance(catalog["default_surface"], str) and catalog["default_surface"] in ids, "default surface is not registered")
    return catalog


def render(catalog):
    validate(catalog)
    surfaces = catalog["surfaces"]
    values = {
        "defaultSurface": catalog["default_surface"],
        # Preserve listSurfaces' existing public shape and catalog order.
        "descriptors": [{key: surface[key] for key in ("id", "name", "icon")} for surface in surfaces],
        "eagerSurfaceIds": [surface["id"] for surface in surfaces if surface["loading"] == "eager"],
        "residentStateIds": sorted({surface["resident_state"] for surface in surfaces if surface["resident_state"]}),
        "shortcuts": [{"id": surface["id"], "description": "Toggle Shelllist " + surface["name"]} for surface in surfaces],
    }
    output = ".pragma library\n// Generated by tools/generate-surface-catalog.py from contracts/surface-catalog.json.\n// Do not edit; typed factories stay in SurfaceRegistry.qml.\n\n"
    for name, value in values.items():
        output += f"var {name} = {json.dumps(value, ensure_ascii=False, indent=4)};\n\n"
    output += """// Each registry owns its mutable loading state, even in multi-engine tests.
function initiallyLoaded() {
    const result = {};
    eagerSurfaceIds.forEach(function (id) { result[id] = true; });
    return result;
}

function requiresResidentState(id) {
    return residentStateIds.indexOf(id) !== -1;
}
"""
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--check", action="store_true", help="reject stale output instead of writing")
    args = parser.parse_args()
    try:
        expected = render(json.loads((args.root / "contracts/surface-catalog.json").read_text()))
        output = args.root / "shell/SurfaceCatalog.generated.js"
        if args.check:
            require(output.is_file() and output.read_text() == expected,
                    "stale SurfaceCatalog.generated.js; run python3 tools/generate-surface-catalog.py")
        else:
            output.write_text(expected)
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
